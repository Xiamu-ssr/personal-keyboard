import fs from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {spawn} from 'node:child_process';
import {root,sdkRoot} from '../demo/tools.mjs';
const sdk=await sdkRoot();
await fs.writeFile(path.join(root,'app/local.properties'),'sdk.dir='+sdk+'\n');
const command=process.platform==='win32'?'gradlew.bat':'./gradlew';
const child=spawn(command,[':app:assembleDebug'],{cwd:path.join(root,'app'),stdio:'inherit'});
await new Promise((resolve,reject)=>{child.once('error',reject);child.once('exit',code=>code===0?resolve():reject(Error('Android build failed')));});
const apk=path.join(root,'app/app/build/outputs/apk/debug/app-debug.apk');
const destination=path.join(root,'spec/demo/doudou-keyboard.apk');
await fs.copyFile(apk,destination);
const blob=await fs.readFile(apk);
const version=(await fs.readFile(path.join(root,'app/app/build.gradle'),'utf8')).match(/versionName '([^']+)'/)[1];
const artifact={package:'app.doudou.ime',version,sha256:createHash('sha256').update(blob).digest('hex'),bytes:blob.length,buildType:'debug',production:false,modelsBundled:false};
await fs.writeFile(path.join(root,'spec/demo/artifact.json'),JSON.stringify(artifact,null,2)+'\n');
console.log('APK: '+destination+'\nSHA256 '+artifact.sha256);
